#!/usr/bin/env python3
# Regenerate Arduino settings after editing ID.yaml. Flash again after changes.
import json
from pathlib import Path
import yaml

root = Path(__file__).resolve().parents[1]
data = yaml.safe_load((root / "ID.yaml").read_text())
io, network = data["io"], data["network"]
mapping = {
    "GREEN_BUTTON_PIN": "green_button",
    "RED_BUTTON_PIN": "red_button",
    "SELECTOR_A_PIN": "selector_a",
    "SELECTOR_B_PIN": "selector_b",
    "ESTOP_HEALTHY_PIN": "estop_feedback",
    "PROXIMITY_PIN": "proximity",
    "STEP_PIN": "step",
    "DIR_PIN": "direction",
    "ENABLE_PIN": "enable",
    "TOWER_GREEN_PIN": "tower_green",
    "TOWER_YELLOW_PIN": "tower_yellow",
    "TOWER_RED_PIN": "tower_red",
    "ALARM_PIN": "alarm",
}
lines = [
    "#pragma once",
    "// Generated by tools/apply_id.py; edit ID.yaml.",
    "constexpr bool IO_VERIFIED = " + str(io["verified"]).lower() + ";",
]
for constant, key in mapping.items():
    lines.append(f"constexpr int {constant} = {int(io[key])};")
lines += [
    "constexpr bool ENABLE_ACTIVE_LOW = true;",
    "constexpr bool TOWER_ACTIVE_HIGH = true;",
    "constexpr bool ESTOP_HEALTHY_HIGH = true;",
    "constexpr bool PROXIMITY_ACTIVE_LOW = "
    + str(io["proximity_active_low"]).lower()
    + ";",
    "constexpr bool SELECTOR_ACTIVE_LOW = "
    + str(io["selector_active_low"]).lower()
    + ";",
    "constexpr bool BUTTON_ACTIVE_LOW = " + str(io["buttons_active_low"]).lower() + ";",
    f"constexpr uint32_t MAX_STEP_HZ = {int(io['max_step_hz'])};",
    "constexpr uint32_t WATCHDOG_MS = 500;",
    'static_assert(!IO_VERIFIED || (ESTOP_HEALTHY_PIN >= 0 && MAX_STEP_HZ > 0), "Confirm E-stop feedback and step rate in ID.yaml");',
]
(root / "firmware/project2_io/io_config.h").write_text("\n".join(lines) + "\n")
transport = [
    "#pragma once",
    "// Generated by tools/apply_id.py; edit ID.yaml.",
    "#define PROJECT2_WIFI " + str(int(data["transport"] == "wifi")),
    "constexpr char WIFI_SSID[] = " + json.dumps(network["ssid"]) + ";",
    "constexpr char WIFI_PASSWORD[] = " + json.dumps(network["password"]) + ";",
    "constexpr char AGENT_IP[] = " + json.dumps(network["agent_ip"]) + ";",
    f"constexpr unsigned int AGENT_PORT = {int(network['agent_port'])};",
    f"constexpr unsigned int ROS_DOMAIN = {int(data['ros_domain_id'])};",
]
(root / "firmware/project2_io/transport_config.h").write_text(
    "\n".join(transport) + "\n"
)
print("Arduino configuration updated. Reflash the ESP32 after changes.")
